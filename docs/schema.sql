-- 5. Préstamos
CREATE TABLE public.loans (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    libro_id UUID REFERENCES public.books(id) NOT NULL,
    usuario_id UUID REFERENCES public.profiles(id) NOT NULL,
    fecha_prestamo TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL,
    fecha_devolucion_estimada TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_devolucion_real TIMESTAMP WITH TIME ZONE,
    estado TEXT CHECK (estado IN ('active', 'returned', 'overdue')) DEFAULT 'active',
    renovaciones INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

