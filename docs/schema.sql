-- 4. Libros
CREATE TABLE public.books (
    id UUID DEFAULT gen_random_uuid() PRIMARY KEY,
    titulo TEXT NOT NULL,
    autor TEXT NOT NULL,
    isbn TEXT,
    editorial TEXT,
    año_publicacion INTEGER,
    categoria_id BIGINT REFERENCES public.categories(id),
    ubicacion_id BIGINT REFERENCES public.locations(id),
    cantidad_total INTEGER DEFAULT 1 NOT NULL,
    cantidad_disponible INTEGER DEFAULT 1 NOT NULL,
    codigo_barras TEXT UNIQUE,
    imagen_portada_url TEXT,
    estado TEXT CHECK (estado IN ('disponible', 'prestado', 'dañado', 'perdido')) DEFAULT 'disponible',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT TIMEZONE('utc'::text, NOW()) NOT NULL
);

