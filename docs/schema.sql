-- Triggers y Funciones
-- Actualizar stock al prestar
CREATE OR REPLACE FUNCTION handle_loan_checkout()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE public.books
    SET cantidad_disponible = cantidad_disponible - 1
    WHERE id = NEW.libro_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER on_loan_created
AFTER INSERT ON public.loans
FOR EACH ROW EXECUTE FUNCTION handle_loan_checkout();

-- Actualizar stock al devolver
CREATE OR REPLACE FUNCTION handle_loan_return()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.estado = 'returned' AND OLD.estado != 'returned' THEN
        UPDATE public.books
        SET cantidad_disponible = cantidad_disponible + 1
        WHERE id = NEW.libro_id;
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER on_loan_updated
AFTER UPDATE ON public.loans
FOR EACH ROW EXECUTE FUNCTION handle_loan_return();
